export function scopeFor(subject: TeacherSubject) {
  return EXAM_SCOPE.find(item => item.subject === subject) ?? null;
}

export function totalIndicators() {
  return EXAM_SCOPE.reduce((sum, item) => sum + item.indicators.length, 0);
}
